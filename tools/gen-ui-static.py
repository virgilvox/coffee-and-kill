#!/usr/bin/env python3
"""gen-ui-static.py: the static parts of the page's screens as draw ops for ui.c.

Input: a DOM dump of one screen taken in Chrome at 1280x720 (every element's
untransformed box, borders, shadows, colours, its cumulative transform and its
text lines, positioned by the browser). Output: src/ui_static_<name>.h, a table
of rects, borders, shadows and glyph runs that ui.c paints into the screen's
canvas, so the static screen is the browser's layout to the pixel.

  python3 tools/gen-ui-static.py dump-controls.json controls > src/ui_static_controls.h
"""
import json, re, sys

FONTS = {'Archivo': 'F_MARKER', 'IBM Plex Mono': 'F_TYPE', 'JetBrains Mono': 'F_LCD'}

def rgba(s):
    m = re.match(r'rgba?\(([^)]*)\)', s.strip())
    if not m: return None
    v = [float(x) for x in m.group(1).replace('/', ',').split(',')]
    a = v[3] if len(v) > 3 else 1.0
    return '0x%02x%02x%02x, %.3f' % (int(v[0]), int(v[1]), int(v[2]), a), a

def shadows(s):
    out = []
    for part in re.findall(r'(rgba?\([^)]*\))\s+(-?[\d.]+)px\s+(-?[\d.]+)px(?:\s+(-?[\d.]+)px)?(?:\s+(-?[\d.]+)px)?', s):
        out.append((rgba(part[0])[0], float(part[1]), float(part[2]), float(part[3] or 0), float(part[4] or 0)))
    return out

def side(s):
    w, style, *col = s.split(' ', 2)
    return float(w[:-2]), style, ' '.join(col)

def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def main():
    d = json.load(open(sys.argv[1])); name = sys.argv[2]
    skip = set(sys.argv[3].split(',')) if len(sys.argv) > 3 else set()
    ops = []
    for o in d:
        if o['cls'] and set(o['cls'].split()) & skip: continue
        if o['tag'] in ('path', 'g', 'section'): continue
        m = '{%s}' % ', '.join('%g' % v for v in o['m'])
        if o['tag'] == 'svg':   # the HeatSync mark (ui_mark.h), drawn from its own raster
            ops.append('{OP_MARK, 0, 0, 0, %g, %g, %g, %g, 0, 1, %s, %g, NULL}' % (o['x'], o['y'], o['w'], o['h'], m, o['op']))
            continue
        x, y, w, h = o['x'], o['y'], o['w'], o['h']
        op = o['op']
        for sh in shadows(o['bs']):
            ops.append('{OP_RECT, 0, 0, 0, %g, %g, %g, %g, %s, %s, %g, NULL}' % (x + sh[1] - sh[4], y + sh[2] - sh[4], w + 2 * sh[4], h + 2 * sh[4], sh[0], m, op))
        bg = rgba(o['bg'])
        if bg and bg[1] > 0:
            ops.append('{OP_RECT, 0, 0, 0, %g, %g, %g, %g, %s, %s, %g, NULL}' % (x, y, w, h, bg[0], m, op))
        for s, k in ((o['bt'], 'T'), (o['br'], 'R'), (o['bb'], 'B'), (o['bl'], 'L')):
            bw, style, col = side(s)
            if bw <= 0 or style == 'none': continue
            c = rgba(col)[0]
            kind = 'OP_DASH' if style == 'dashed' else 'OP_RECT'
            if k == 'T': r = (x, y, w, bw)
            elif k == 'B': r = (x, y + h - bw, w, bw)
            elif k == 'L': r = (x, y, bw, h)
            else: r = (x + w - bw, y, bw, h)
            ops.append('{%s, 0, 0, 0, %g, %g, %g, %g, %s, %s, %g, NULL}' % ((kind,) + r + (c, m, op)))
        if o['lines']:
            f = FONTS.get(o['ff'], 'F_TYPE')
            col = rgba(o['col'])[0]
            ts = shadows(o['ts'])
            for L in o['lines']:
                for sh in reversed(ts):
                    ops.append('{OP_TEXT, %s, %g, %g, %g, %g, %g, %g, %s, %s, %g, %s}' % (f, o['fs'], o['ls'], L['x'] + sh[1], L['y'] + sh[2], L['w'], L['h'], sh[0], m, op, cstr(L['text'])))
                ops.append('{OP_TEXT, %s, %g, %g, %g, %g, %g, %g, %s, %s, %g, %s}' % (f, o['fs'], o['ls'], L['x'], L['y'], L['w'], L['h'], col, m, op, cstr(L['text'])))
    print('/* generated by tools/gen-ui-static.py from a Chrome DOM dump of the page (%s) */' % name)
    print('static const uiop STATIC_%s[] = {' % name.upper())
    for s in ops: print('  ' + s + ',')
    print('};')

main()
